#!/usr/bin/env python3
"""Regenerate the editor's and the debugger's Python path from what is on disk.

    venv/bin/python harness/sync_paths.py          # rewrite
    venv/bin/python harness/sync_paths.py --check  # exit 1 if stale

Run it after adding or removing a service package, or changing SNC_SERVICES.
setup.sh runs it once.

The service packages are not an installable package: on a controller each
packages/<pkg>/ is flattened into one modules dir and the pyapi appends every
directory holding a .py to sys.path. Reproducing that means naming each
package directory, and neither a VS Code envFile nor
python.analysis.extraPaths can glob, so the list is generated here from the
same clixon_env.python_paths() the local pyapi uses.

It writes the list twice: as PYTHONPATH in .vscode/services.env (running and
debugging) and as python.analysis.extraPaths in .vscode/settings.json
(Pylance, which does not reliably pick up an envFile's PYTHONPATH).
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from clixon_env import ROOT, python_paths  # noqa: E402

ENV_FILE = os.path.join(ROOT, ".vscode", "services.env")
SETTINGS = os.path.join(ROOT, ".vscode", "settings.json")

EXTRA_PATHS = re.compile(r'"python\.analysis\.extraPaths"\s*:\s*\[[^\]]*\]')

ENV_HEADER = """\
# Generated by harness/sync_paths.py -- do not hand-edit.
"""


def _env_path(path: str) -> str:
    """Relative to the repo root where possible (a checkout kept elsewhere
    with SNC_SERVICES stays absolute)."""
    relative = os.path.relpath(path, ROOT)
    return path if relative.startswith("..") else relative


def _settings_path(path: str) -> str:
    relative = os.path.relpath(path, ROOT)
    return path if relative.startswith("..") else "${workspaceFolder}/" + relative


def render_env(existing: str, paths) -> str:
    return ENV_HEADER + "PYTHONPATH=" + ":".join(_env_path(p) for p in paths) + "\n"


def render_settings(existing: str, paths) -> str:
    block = ['"python.analysis.extraPaths": [']
    block += [f'        "{_settings_path(p)}",' for p in paths]
    block[-1] = block[-1].rstrip(",")
    block.append("    ]")
    new, count = EXTRA_PATHS.subn(lambda _: "\n".join(block), existing)
    if count != 1:
        raise SystemExit(f"expected one python.analysis.extraPaths block in "
                         f"{SETTINGS}, found {count}; fix it by hand")
    return new


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Do not write; exit 1 if out of date")
    args = parser.parse_args(argv)

    paths = python_paths()
    stale = []
    for path, renderer in ((ENV_FILE, render_env), (SETTINGS, render_settings)):
        try:
            existing = open(path).read()
        except OSError:
            existing = ""
        wanted = renderer(existing, paths)
        if existing != wanted:
            stale.append((path, wanted))

    if not stale:
        print(f"up to date ({len(paths)} paths)")
        return 0
    if args.check:
        for path, _ in stale:
            print(f"{os.path.relpath(path, ROOT)} is out of date", file=sys.stderr)
        return 1
    for path, wanted in stale:
        with open(path, "w") as fh:
            fh.write(wanted)
        print(f"wrote {os.path.relpath(path, ROOT)} ({len(paths)} paths)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
